"""Fail on pyright errors that are not in the committed baseline.

graphify carries a pyright backlog (mostly Optional narrowing that pyright
can't follow through untyped tree-sitter nodes), so a plain ``pyright`` run is
never clean and nobody can tell a new error from an old one. This compares a
run against ``tools/pyright_baseline.json`` and fails only when an error is
new, so the backlog can shrink over time without blocking unrelated work.

Usage (from the repo root, with ``uv sync --all-extras``):

    uv run python -m tools.pyright_baseline            # check
    uv run python -m tools.pyright_baseline --update   # rewrite the baseline

An error is keyed by file, rule and message, not line number, so edits that
only move existing errors don't count as new ones. ``reportMissingImports``
and ``reportMissingModuleSource`` are left out: which optional packages
install depends on the Python version (graspologic vs graspologic-native,
faster-whisper, tomllib), and those were the only differences between 3.10,
3.12 and 3.13. Without the optional extras pyright sees fewer types and
reports a subset of the baseline, so a check still can't fail falsely, but
``--update`` refuses to run, because it would drop those entries.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = Path(__file__).resolve().parent / "pyright_baseline.json"

# Depend on the interpreter's installed packages, not on graphify's code.
ENVIRONMENT_RULES = frozenset({"reportMissingImports", "reportMissingModuleSource"})

# Present only with `uv sync --all-extras`; each changes what pyright can type.
EXTRAS_PROBES = ("docx", "mcp", "neo4j", "psycopg", "openpyxl", "matplotlib")

Key = tuple[str, str]  # (relative file, "rule: message")


def _relative(path: str) -> str:
    try:
        return Path(path).resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return Path(path).as_posix()


def _key(diag: dict) -> Key | None:
    if diag.get("severity") != "error":
        return None
    rule = diag.get("rule", "")
    if rule in ENVIRONMENT_RULES:
        return None
    message = diag.get("message", "").splitlines()[0].replace(str(ROOT), "")
    return _relative(diag["file"]), f"{rule}: {message}"


def count_errors(report: dict) -> Counter[Key]:
    counts: Counter[Key] = Counter()
    for diag in report.get("generalDiagnostics", []):
        key = _key(diag)
        if key is not None:
            counts[key] += 1
    return counts


def load_baseline(path: Path | None = None) -> tuple[Counter[Key], str]:
    data = json.loads((path or BASELINE).read_text(encoding="utf-8"))
    counts: Counter[Key] = Counter()
    for file, entries in data.get("errors", {}).items():
        for entry, n in entries.items():
            counts[(file, entry)] = n
    return counts, data.get("pyright_version", "")


def dump_baseline(counts: Counter[Key], version: str, path: Path | None = None) -> None:
    files: dict[str, dict[str, int]] = {}
    for (file, entry), n in sorted(counts.items()):
        files.setdefault(file, {})[entry] = n
    data = {
        "_comment": "Generated by `python -m tools.pyright_baseline --update`; do not edit by hand.",
        "pyright_version": version,
        "total": sum(counts.values()),
        "errors": files,
    }
    (path or BASELINE).write_text(
        json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def compare(current: Counter[Key], baseline: Counter[Key]) -> tuple[Counter[Key], int]:
    """Return (errors above the baseline per key, number of baseline errors gone)."""
    new = Counter({k: n - baseline[k] for k, n in current.items() if n > baseline[k]})
    fixed = sum(n - current[k] for k, n in baseline.items() if n > current[k])
    return new, fixed


def run_pyright() -> dict:
    proc = subprocess.run(
        [sys.executable, "-m", "pyright", "--outputjson"],
        cwd=ROOT, capture_output=True, text=True,
    )
    # pyright exits 1 when it reports errors; anything else means it didn't run.
    if proc.returncode not in (0, 1):
        raise RuntimeError(f"pyright exited {proc.returncode}: {proc.stderr.strip()[:500]}")
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"pyright did not print JSON: {exc}") from exc


def _missing_extras() -> list[str]:
    return [name for name in EXTRAS_PROBES if importlib.util.find_spec(name) is None]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Fail on pyright errors that are not in the committed baseline.")
    parser.add_argument("--update", action="store_true", help="rewrite the baseline from this run")
    parser.add_argument("--report", type=Path, help="use a saved `pyright --outputjson` report")
    args = parser.parse_args(argv)

    try:
        report = json.loads(args.report.read_text()) if args.report else run_pyright()
    except (OSError, RuntimeError, json.JSONDecodeError) as exc:
        print(f"pyright-baseline: {exc}", file=sys.stderr)
        return 2
    current = count_errors(report)
    version = report.get("version", "")
    missing = _missing_extras()

    if args.update:
        if missing:
            print("pyright-baseline: refusing to update without the optional extras "
                  f"(missing: {', '.join(missing)}); run `uv sync --all-extras` first.",
                  file=sys.stderr)
            return 2
        dump_baseline(current, version)
        print(f"pyright-baseline: wrote {sum(current.values())} errors to "
              f"{_relative(str(BASELINE))}")
        return 0

    baseline, base_version = load_baseline()
    if base_version and version and base_version != version:
        print(f"pyright-baseline: note: baseline recorded with pyright {base_version}, "
              f"running {version}; messages may differ.")
    new, fixed = compare(current, baseline)

    if new:
        print(f"pyright-baseline: {sum(new.values())} new pyright error(s):\n")
        by_key: dict[Key, list[str]] = {}
        for diag in report.get("generalDiagnostics", []):
            diag_key = _key(diag)
            if diag_key is not None and diag_key in new:
                start = diag["range"]["start"]
                by_key.setdefault(diag_key, []).append(
                    f"{diag_key[0]}:{start['line'] + 1}:{start['character'] + 1}")
        for key, n in sorted(new.items()):
            places = by_key.get(key, [key[0]])
            extra = "" if len(places) == n else f" ({n} new of {len(places)} like it)"
            print(f"  {key[1]}{extra}")
            for place in places:
                print(f"    {place}")
        print("\nFix them, or if they are intended, run "
              "`uv run python -m tools.pyright_baseline --update` and commit the baseline.")
        return 1

    print(f"pyright-baseline: no new errors ({sum(current.values())} known, "
          f"baseline {sum(baseline.values())}).")
    if fixed and not missing:
        print(f"pyright-baseline: {fixed} baseline error(s) no longer occur; run with "
              "--update to lock that in.")
    elif missing:
        print("pyright-baseline: note: optional extras not installed "
              f"({', '.join(missing)}), so this run sees fewer errors than CI.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
